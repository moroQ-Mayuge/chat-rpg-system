--
-- 母親のタグをそのまま継承させるわけにはいかない。母が「生徒」なら子も
-- 「生徒」になり、幼児が教室に湧く。かといって空のままだとどの部屋にも
-- 出てこないので、「この世界で子はどこに居るのか」を作者が決められる形にする。
-- 現代学園ファンタジーなら「家族」を入れておけば自宅の部屋に出るようになる。
--
-- 空欄なら自動出現はしない(明示的なイベントや手動のスロット割当でだけ登場する)。
