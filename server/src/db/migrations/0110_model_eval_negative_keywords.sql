-- 既定のネガティブ文脈シナリオの禁止語を広げる。
-- Gemma4で実走したところ、2ターン目で「よし。だが、二度と強要してくるなよ。」と
-- 陥落したのに、禁止語リストに「よし」「わかった」等が無く見逃していた。
-- 承諾の言い方は「いいよ」以外にも幅があるため、実際に観測された語を足す。
UPDATE model_eval_scenarios
SET turns = replace(
  turns,
  '"forbid_keywords":["いいよ","いいわ","どうぞ","してもいい","許す","構わない"]',
  '"forbid_keywords":["いいよ","いいわ","どうぞ","してもいい","許す","構わない","よし","わかった","分かった","仕方ない","一度だけ","一回だけ","好きにしろ","勝手にしろ"]'
)
WHERE category = 'negative';
