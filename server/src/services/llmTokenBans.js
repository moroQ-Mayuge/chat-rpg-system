// 表音文字。字母を全列挙すればその言語は書けなくなる。
//
// 【ギリシャ文字を意図的に除外している】ギリシャ文字はJIS X 0208にも収録され、
// 日本語の文中でも記号として普通に使われる(α版・β・μ・Ω・π・θ)。ギリシャ語の
// 混入は報告されていないので、正当な用途を潰すリスクの方が大きいと判断した。
// キリル文字も同じくJISには入っているが、日本語の文中に現れることはまず無く、
// ロシア語混入は実際に報告されているので対象に含める。
//
// 【何を入れて何を諦めたか】予算が約768件しかないのに対し、日本語・英語以外の
// 文字を本当に全部覆うには15,000字以上必要で、**完全な網羅は原理的に不可能**。
// そこで「実プレイで自然に混ざってくる形」を優先して配分してある:
//   入れた: キリル/ヘブライ(母音記号込み)/アラビア(補助記号・拡張字母込み)/
//           ハングル高頻度音節/簡体字
//   諦めた: アラビア文字表示形A・B、ハングル字母(U+1100-11FF)、タイ文字、
//           デーヴァナーガリー、その他の文字体系
// 諦めた側は、基本形を禁止された時にモデルが「迂回先」として使う異表記が中心。
// 「韓国語で書け」のように明示的に指示された時はそちらへ逃げて出力され得るが、
// 日本語のロールプレイ中に自然に混ざるケースでは基本形が使われるので、実用上は
// こちらの配分の方が効く。逆に言えば、指示された言語を確実に止める用途には
// この方式は使えない（GBNFなら止められるが、生成速度が100分の1になる）。
const PHONETIC_SCRIPT_RANGES = [
  [0x0401, 0x0401], // Ё
  [0x0410, 0x044f], // キリル文字 А-я（ロシア語ほか）
  [0x0451, 0x0451], // ё
  [0x05b0, 0x05f4], // ヘブライ文字（母音記号ニクダー込み。記号だけで抜けるため）
  [0x0621, 0x06d3], // アラビア文字（字母・補助記号・拡張字母。ٱ(U+0671)等も含む）
];

function expandRange(start, end) {
  const chars = [];
  for (let cp = start; cp <= end; cp += 1) {
    const ch = String.fromCodePoint(cp);
    // 未割り当てコードポイントは予算を食うだけなので落とす。
    if (/\p{L}|\p{N}|\p{M}/u.test(ch)) chars.push(ch);
  }
  return chars;
}

const PHONETIC_CHARS = PHONETIC_SCRIPT_RANGES.flatMap(([a, b]) => expandRange(a, b));

// banned_tokensは「この部分文字列を含む語彙トークンを禁止する」という指定なので、
// 1文字ずつ渡せばその文字を含むトークンがすべて禁止される。全てASCII外かつ
// 仮名・和文約物・全角形の範囲外なので、英語・日本語のトークンは巻き込まない。
const FOREIGN_CHARS = [...new Set([...PHONETIC_CHARS, ...HANGUL_COMMON_SYLLABLES, ...SIMPLIFIED_ONLY_CHARS])];

// 実測した上限(755件は有効/805件は無効)に対する安全余裕。超過分は黙って無視され、
// 「設定はONなのに効いていない」という最悪の壊れ方をするので、起動時に落とす。
const BUDGET = 700;
if (FOREIGN_CHARS.length > BUDGET) {
  throw new Error(
    `llmTokenBans: 禁止トークンが${FOREIGN_CHARS.length}件で上限(${BUDGET})を超えています。` +
      'KoboldCppは超過分を黙って捨てるため、どれかの文字体系を削って予算内に収めてください。',
  );
}

