// 確認済み——JISに入っている＝日本語で使う字なので、この判定が根拠になる。
//
// 追加・変更したら次を実行し、出力が「なし」であることを確認する（JISに収録された
// ギリシャ・キリル文字を巻き込まないよう、判定は漢字の範囲に限定している）:
//   node --input-type=module -e "
//   import iconv from 'iconv-lite';
//   import { __testing } from './server/src/services/llmTokenBans.js';
//   const bad = __testing.SIMPLIFIED_ONLY_CHARS
//     .filter((c) => iconv.decode(iconv.encode(c, 'Shift_JIS'), 'Shift_JIS') === c);
