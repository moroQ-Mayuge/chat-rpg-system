// LLM出力から日本語・英語以外の文字を締め出す禁止トークン一覧
// （KoboldCppのbanned_tokensパラメータ用）。
//
// 当初はGBNF文法(grammar)で「許可する文字範囲のホワイトリスト」を与えていたが、
// 候補トークンごとに全文字範囲を照合するため生成が実用に耐えないほど遅くなった。
// banned_tokensは指定した部分文字列を含む語彙トークンを禁止する仕組みで、禁止
// トークンIDの集合を作るのが1リクエストにつき1回で済み、生成長に比例したコストが
// 乗らない。
//
// 実測（Gemma-4-E4B、160トークン生成・貪欲デコード）:
//   禁止なし 57〜61 tok/s ／ token ban 43〜46 tok/s（無効比75%前後）
//   GBNF 0.6 tok/s（無効比1%。106トークンの生成に178秒）
// token banはGBNFの約75倍速い。
//
// 【重要: 禁止リストには約768件の上限がある】KoboldCppは超過分を黙って捨てる。
// 実測では755件までは末尾の項目も効いたが、805件では効かなくなった
// (koboldcpp.py の logit_bias_max = 512 と同種の上限と思われる)。
// 15,824件を渡した版では大半が無視され、韓国語・アラビア語・タイ語・ヒンディー語が
// そのまま出力された——「リストを増やすほど守りが堅くなる」わけではない。
// 下の BUDGET はこの上限に対する安全余裕込みの自己申告値で、超えたら起動時に
// 例外を投げる（黙って効かなくなるのが一番たちが悪いため）。
//
// この予算制約があるため、文字体系ごとに「その言語が成立しなくなる最小限の字」を
// 選ぶ設計にしてある:
//   ・表音文字(キリル/ヘブライ/アラビア/タイ/デーヴァナーガリー)は字母を全列挙。
//     字母が1つも使えなければその言語は書けないので、これで完全にブロックされる。
//   ・ハングルは11,172字あり全列挙できないので高頻度音節のみ。韓国語の文は
//     助詞・語尾を避けて書けないため実用上は成立しなくなるが、稀な音節だけで
//     構成された語（固有名詞など）は通り得る。
//   ・漢字は日本語と中国語でコードポイントが共通なので、簡体字固有の字形しか
//     弾けない。繁体字や共通漢字だけで書かれた中国語は通過する——これは方式を
//     問わず原理的に避けられない。

// 日本語表記に現れない簡体字。中国語の高頻度な機能語・動詞・常用字を並べてあり、
// これらが1字も使えないと中国語の文はほぼ成立しない。
//
// 【この配列を編集する時は必ず検証すること】新旧字体が同じコードポイントの漢字
